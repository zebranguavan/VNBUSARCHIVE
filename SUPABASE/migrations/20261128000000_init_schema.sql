create function public.get_home_stats(pref_filter text default 'both')
returns table (total_photos bigint, total_vehicles bigint, total_routes bigint)
language sql stable set search_path = public as $$
  select count(*)::bigint,
         count(distinct p.license_plate)::bigint,
         count(distinct nullif(p.route_no, ''))::bigint
  from public.photos p
  left join public.profiles pr on pr.id = p.uploader_id
  where p.status = 'approved'
    and (pref_filter is null or pref_filter = 'both' or p.type = pref_filter)
    and coalesce(pr.ban_status ->> 'banned', 'false') <> 'true';
$$;

create function public.get_operator_stats(op_name text)
returns table (total_photos bigint, total_views bigint, total_vehicles bigint, total_routes bigint)
language sql stable set search_path = public as $$
  select count(*)::bigint,
         coalesce(sum(p.views), 0)::bigint,
         count(distinct p.license_plate)::bigint,
         count(distinct nullif(coalesce(p.borrowed_route, p.route_no), ''))::bigint
  from public.photos p
  left join public.profiles pr on pr.id = p.uploader_id
  where p.status = 'approved'
    and lower(p.operator) = lower(op_name)
    and coalesce(pr.ban_status ->> 'banned', 'false') <> 'true';
$$;

create function public.get_model_stats(mdl_name text)
returns table (total_photos bigint, total_views bigint, total_vehicles bigint, total_ops bigint)
language sql stable set search_path = public as $$
  select count(*)::bigint,
         coalesce(sum(p.views), 0)::bigint,
         count(distinct upper(p.license_plate))::bigint,
         count(distinct lower(p.operator)) filter (where p.operator is not null and p.operator <> '---')::bigint
  from public.photos p
  join public.vehicles v on v.license_plate = p.license_plate
  left join public.profiles pr on pr.id = p.uploader_id
  where p.status = 'approved'
    and v.model = mdl_name
    and coalesce(pr.ban_status ->> 'banned', 'false') <> 'true';
$$;

create function public.get_operator_plates(op_name text)
returns table (license_plate text, route text, model text)
language sql stable set search_path = public as $$
  select distinct on (p.license_plate)
         p.license_plate,
         coalesce(p.borrowed_route, p.route_no),
         v.model
  from public.photos p
  left join public.vehicles v on v.license_plate = p.license_plate
  left join public.profiles pr on pr.id = p.uploader_id
  where p.status = 'approved'
    and p.license_plate is not null
    and lower(p.operator) = lower(op_name)
    and coalesce(pr.ban_status ->> 'banned', 'false') <> 'true'
  order by p.license_plate, p.taken_at desc nulls last, p.id desc;
$$;

-- SECURITY DEFINER vì cần đọc photo_views_log (khách không có quyền đọc bảng này); chỉ trả ảnh đã duyệt.
create function public.get_trending_photos_24h(filter_type text default 'both', limit_num integer default 5)
returns setof public.photos
language sql stable security definer set search_path = public as $$
  select p.*
  from public.photos p
  left join (
    select photo_id, count(*) as c
    from public.photo_views_log
    where created_at > now() - interval '24 hours'
    group by photo_id
  ) v on v.photo_id = p.id
  left join public.profiles pr on pr.id = p.uploader_id
  where p.status = 'approved'
    and (filter_type is null or filter_type = 'both' or p.type = filter_type)
    and coalesce(pr.ban_status ->> 'banned', 'false') <> 'true'
  order by coalesce(v.c, 0) desc, p.views desc, p.id desc
  limit greatest(coalesce(limit_num, 5), 1);
$$;

create function public.get_user_profile_stats(target_user_id uuid, is_own_profile boolean default false)
returns table (total_photos bigint, total_views bigint, total_likes bigint)
language sql stable set search_path = public as $$
  select count(*)::bigint,
         coalesce(sum(p.views), 0)::bigint,
         (select count(*)
            from public.photo_likes l
            join public.photos p2 on p2.id = l.photo_id
           where p2.uploader_id = target_user_id
             and (case when is_own_profile then p2.status <> 'denied' else p2.status = 'approved' end))::bigint
  from public.photos p
  where p.uploader_id = target_user_id
    and (case when is_own_profile then p.status <> 'denied' else p.status = 'approved' end);
$$;

