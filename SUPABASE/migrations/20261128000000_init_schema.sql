create function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select role in ('admin', 'manager') from public.profiles where id = auth.uid()), false);
$$;

-- Người được xem ảnh chưa duyệt: quản trị viên + phân quyền phụ 'quality_aud'
create function public.is_reviewer() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select role in ('admin', 'manager') or 'quality_aud' = any (subroles)
                   from public.profiles where id = auth.uid()), false);
$$;

create function public.is_banned() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select (ban_status ->> 'banned') = 'true' from public.profiles where id = auth.uid()), false);
$$;

