-- Người dùng KHÔNG được tự đặt discord_custom_role_id (server dùng giá trị này để cấp role Discord);
-- chỉ được đặt về NULL (hủy liên kết).
create function public.profiles_guard() returns trigger
language plpgsql as $$
begin
  if current_user in ('anon', 'authenticated') then
    new.id := old.id;
    if new.discord_custom_role_id is not null then
      new.discord_custom_role_id := old.discord_custom_role_id;
    end if;
  end if;
  return new;
end $$;
create trigger profiles_guard_trg before update on public.profiles
  for each row execute function public.profiles_guard();

-- Bảng ảnh có khóa ngoại tới vehicles (để PostgREST nhúng vehicles(model)); tự tạo xe nếu chưa có
-- để việc tải ảnh lên không bị lỗi khóa ngoại.
create function public.photos_ensure_vehicle() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.license_plate = '' then new.license_plate := null; end if;
  if new.license_plate is not null then
    insert into public.vehicles (license_plate) values (new.license_plate) on conflict (license_plate) do nothing;
  end if;
  return new;
end $$;
create trigger photos_ensure_vehicle_trg before insert or update of license_plate on public.photos
  for each row execute function public.photos_ensure_vehicle();

-- Tăng lượt xem khi có bản ghi xem. Trình duyệt KHÔNG được sửa photos.views trực tiếp.
create function public.bump_photo_views() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  update public.photos set views = views + 1 where id = new.photo_id;
  return null;
end $$;
create trigger photo_views_log_bump_trg after insert on public.photo_views_log
  for each row execute function public.bump_photo_views();

