-- 4. HÀM RPC (TÙY CHỌN: giao diện có sẵn cách dự phòng nếu các hàm này không tồn tại/lỗi)
--    Tên hàm và tham số khớp đúng cách trình duyệt gọi. Nội dung là suy đoán từ cách giao diện dùng kết quả.
